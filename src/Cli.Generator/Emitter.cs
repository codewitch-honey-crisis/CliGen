using System.Globalization;
using System.Linq;
using System.Text;

namespace Cli.Generator
{
	/// <summary>Writes the generated partial type for a <see cref="TypeModel"/>.</summary>
	internal static class Emitter
	{

		sealed class Writer
		{
			readonly StringBuilder _sb = new StringBuilder();
			int _indent;

			public Writer Line(string text = "")
			{
				if (text.Length > 0) _sb.Append('\t', _indent).Append(text);
				_sb.Append('\n');
				return this;
			}

			public Writer Open(string text)
			{
				Line(text);
				Line("{");
				++_indent;
				return this;
			}

			public Writer Close(string suffix = "")
			{
				--_indent;
				return Line("}" + suffix);
			}

			public override string ToString() => _sb.ToString();
		}

		/// <param name="utilityNamespace">The namespace CliUtility and CmdException were emitted into ("" for the global namespace).</param>
		public static string Emit(TypeModel m, string utilityNamespace)
		{
			var w = new Writer();
			w.Line("// <auto-generated/>");
			w.Line("// Generated by Cli.Generator from [CmdArg] members of " + m.TypeName + ".");
			w.Line("#pragma warning disable");
			if (m.Namespace != null) w.Open("namespace " + m.Namespace);
			foreach (var c in m.ContainerDeclarations) w.Open(c);
			w.Open(m.GenerateDispose ? m.TypeDeclaration + " : global::System.IDisposable" : m.TypeDeclaration);

			string t = m.FullName;
			string util = utilityNamespace.Length == 0 ? "global::CliUtility" : "global::" + utilityNamespace + ".CliUtility";
			string exc = utilityNamespace.Length == 0 ? "global::CmdException" : "global::" + utilityNamespace + ".CmdException";
			string G = util + ".Generated";
			

			if (m.HasNamedGroups)
			{
				w.Line("/// <summary>The group (usage form) that matched when this instance was parsed.</summary>");
				w.Line("public string ArgumentGroup { get; private set; }");
				w.Line();
			}

			// Parse
			w.Line("/// <summary>");
			w.Line("/// Parses a full command line, including the executable as its first element, as found in <see cref=\"global::System.Environment.CommandLine\"/>.");
			w.Line("/// </summary>");
			w.Line("/// <param name=\"commandLine\">The command line, or null to use <see cref=\"global::System.Environment.CommandLine\"/>.</param>");
			w.Line("/// <exception cref=\"" + exc + "\">The arguments are invalid, or help was requested.</exception>");
			w.Open("public static " + t + " Parse(string commandLine = null)");
			w.Line("if (commandLine == null) commandLine = global::System.Environment.CommandLine;");
			w.Line("return __CliBind(" + G + ".TokenizeCommandLine(commandLine, true));");
			w.Close();
			w.Line();

			w.Line("/// <summary>Parses a full command line, including the executable. Returns false and sets <paramref name=\"error\"/> when the arguments are invalid or help was requested.</summary>");
			TryAccess(w, m);
			w.Open("static bool TryParse(string commandLine, out " + t + " result, out " + exc + " error)");
			w.Open("try");
			w.Line("result = Parse(commandLine);");
			w.Line("error = null;");
			w.Line("return true;");
			w.Close();
			w.Open("catch (" + exc + " ex)");
			w.Line("result = default(" + t + ");");
			w.Line("error = ex;");
			w.Line("return false;");
			w.Close();
			w.Close();
			w.Line();

			// Create
			w.Line("/// <summary>Creates an instance from arguments that are already split, such as the args passed to Main. The executable is not included.</summary>");
			w.Line("/// <exception cref=\"" + exc + "\">The arguments are invalid, or help was requested.</exception>");
			w.Open("public static " + t + " Create(global::System.Collections.Generic.IEnumerable<string> args)");
			w.Line("if (args == null) throw new global::System.ArgumentNullException(\"args\");");
			w.Line("return __CliBind(" + G + ".TokenizeArgs(args));");
			w.Close();
			w.Line();

			w.Line("/// <summary>Creates an instance from arguments that are already split. Returns false and sets <paramref name=\"error\"/> when the arguments are invalid or help was requested.</summary>");
			TryAccess(w, m);
			w.Open("static bool TryCreate(global::System.Collections.Generic.IEnumerable<string> args, out " + t + " result, out " + exc + " error)");
			w.Open("try");
			w.Line("result = Create(args);");
			w.Line("error = null;");
			w.Line("return true;");
			w.Close();
			w.Open("catch (" + exc + " ex)");
			w.Line("result = default(" + t + ");");
			w.Line("error = ex;");
			w.Line("return false;");
			w.Close();
			w.Close();
			w.Line();

			EmitUsage(w, m, G);
			EmitSpecs(w, m, G);
			EmitBind(w, m, G, exc);
			if (m.GenerateDispose) EmitDispose(w, m, G);

			w.Close();
			foreach (var _ in m.ContainerDeclarations) w.Close();
			if (m.Namespace != null) w.Close();
			return w.ToString();
		}

		/// <summary>
		/// The Try* methods expose CmdException, which is internal unless CLI_PUBLIC is defined.
		/// On a public type they can only be public when CmdException is.
		/// </summary>
		static void TryAccess(Writer w, TypeModel m)
		{
			if (!m.IsPublic)
			{
				w.Line("public");
				return;
			}
			w.Line("#if CLI_PUBLIC");
			w.Line("public");
			w.Line("#else");
			w.Line("internal");
			w.Line("#endif");
		}

		static void EmitUsage(Writer w, TypeModel m, string G)
		{
			w.Open("static " + G + ".UsageGroup[] __CliUsageGroups()");
			w.Line("var __d = new " + m.FullName + "();");
			w.Open("return new " + G + ".UsageGroup[]");
			for (int g = 0; g < m.Groups.Count; ++g)
			{
				var grp = m.Groups[g];
				var lefts = string.Join(", ", grp.Lefts.Select(Lit));
				var descs = string.Join(", ", grp.RowIds.Select(id =>
				{
					var a = m.Args[id];
					string d = Lit(a.Description);
					return a.ShowDefault ? G + ".WithDefault(" + d + ", __d." + Ident(a.MemberName) + ")" : d;
				}));
				w.Line("new " + G + ".UsageGroup(" + Lit(grp.Name) + ", " + Lit(grp.Synopsis) + ", new string[] { " + lefts + " }, new string[] { " + descs + " })"
					+ (g < m.Groups.Count - 1 ? "," : ""));
			}
			w.Close(";");
			w.Close();
			w.Line();

			w.Line("/// <summary>Returns the full usage screen, wrapped to <paramref name=\"width\"/> characters (0 uses the console width).</summary>");
			w.Open("public static string GetUsage(int width = 0)");
			w.Line("return " + G + ".BuildUsage(typeof(" + m.FullName + ").Assembly, " + Lit(m.ExeName) + ", " + Lit(m.Description) + ", __CliUsageGroups(), width);");
			w.Close();
			w.Line();

			string groupDoc = m.HasNamedGroups
				? "The group (usage form) to describe, or null for the first one: " + string.Join(", ", m.Groups.Select(g => "\"" + g.Name + "\"")) + "."
				: "Leave null; this type has a single usage form.";
			w.Line("/// <summary>Returns the argument synopsis, e.g. <c>&lt;input&gt; [--verbose]</c>, wrapped to <paramref name=\"width\"/>.</summary>");
			w.Line("/// <param name=\"width\">The width to wrap to, or 0 for the console width.</param>");
			w.Line("/// <param name=\"startOffset\">The column the synopsis starts at, after whatever you've already written (such as the program name).</param>");
			w.Line("/// <param name=\"group\">" + groupDoc + "</param>");
			w.Open("public static string GetUsageArguments(int width = 0, int startOffset = 0, string group = null)");
			w.Line("return " + G + ".Synopsis(" + G + ".FindGroup(__CliUsageGroups(), group), width, startOffset);");
			w.Close();
			w.Line();

			w.Line("/// <summary>Returns the table of arguments and their descriptions, wrapped to <paramref name=\"width\"/>.</summary>");
			w.Line("/// <param name=\"width\">The width to wrap to, or 0 for the console width.</param>");
			w.Line("/// <param name=\"group\">" + groupDoc + "</param>");
			w.Open("public static string GetUsageDescriptions(int width = 0, string group = null)");
			w.Line("return " + G + ".Descriptions(" + G + ".FindGroup(__CliUsageGroups(), group), width);");
			w.Close();
			w.Line();

			w.Line("/// <summary>Writes the usage text to <paramref name=\"writer\"/> (standard error when null).</summary>");
			w.Open("public static void PrintUsage(global::System.IO.TextWriter writer = null, int width = 0)");
			w.Line("(writer ?? global::System.Console.Error).Write(GetUsage(width));");
			w.Close();
			w.Line();
		}

		static void EmitSpecs(Writer w, TypeModel m, string G)
		{
			w.Line("static " + G + ".GroupSpec[] __cliGroups;");
			w.Line();
			w.Open("static " + G + ".GroupSpec[] __CliGetGroups()");
			w.Line("var __g = __cliGroups;");
			w.Line("if (__g != null) return __g;");
			foreach (var a in m.Args)
			{
				w.Line("var __a" + a.Id + " = new " + G + ".ArgSpec(" + a.Id + ", " + Lit(a.IsPositional ? null : a.LongName) + ", "
					+ CharLit(a.ShortName) + ", " + a.Position + ", " + G + ".ArgKind." + a.Kind + ", "
					+ (a.Required ? "true" : "false") + ", " + Lit(a.ValueName) + ");");
			}
			w.Open("__g = new " + G + ".GroupSpec[]");
			for (int g = 0; g < m.Groups.Count; ++g)
			{
				var grp = m.Groups[g];
				w.Line("new " + G + ".GroupSpec(" + Lit(grp.Name)
					+ ", new " + G + ".ArgSpec[] { " + string.Join(", ", grp.Positional.Select(id => "__a" + id)) + " }"
					+ ", new " + G + ".ArgSpec[] { " + string.Join(", ", grp.Named.Select(id => "__a" + id)) + " })"
					+ (g < m.Groups.Count - 1 ? "," : ""));
			}
			w.Close(";");
			w.Line("__cliGroups = __g;");
			w.Line("return __g;");
			w.Close();
			w.Line();
		}

		static void EmitBind(Writer w, TypeModel m, string G, string exc)
		{
			w.Open("static " + m.FullName + " __CliBind(global::System.Collections.Generic.List<" + G + ".Token> tokens)");
			w.Line("var __b = " + G + ".Bind(__CliGetGroups(), tokens, " + m.Args.Count + ");");
			w.Line("var result = new " + m.FullName + "();");
			w.Line("global::System.Collections.Generic.List<string> __v;");
			w.Line("string __s = null;");
			foreach (var a in m.Args)
			{
				w.Open("if ((__v = __b.Values[" + a.Id + "]) != null)");
				w.Open("try");
				string conv = a.ConvertTemplate.Replace("{G}", G).Replace("{0}", "__s");
				string target = "result." + Ident(a.MemberName);
				switch (a.Shape)
				{
					case CollectionShape.None:
						w.Line("__s = __v[0];");
						w.Line(target + " = " + conv + ";");
						break;
					case CollectionShape.Array:
						w.Line("var __l = new global::System.Collections.Generic.List<" + a.ElementType + ">(__v.Count);");
						w.Open("foreach (var __i in __v)");
						w.Line("__s = __i;");
						w.Line("__l.Add(" + conv + ");");
						w.Close();
						w.Line(target + " = __l.ToArray();");
						break;
					case CollectionShape.Create:
					case CollectionShape.Existing:
						string coll = "global::System.Collections.Generic.ICollection<" + a.ElementType + ">";
						if (a.Shape == CollectionShape.Create)
						{
							w.Line("var __c = " + a.CreateExpression + ";");
						}
						else
						{
							w.Line("var __c = " + target + ";");
							w.Line("if (__c == null) throw new global::System.InvalidOperationException(\"" + a.MemberName + " is null, so values can't be added to it.\");");
							w.Line("((" + coll + ")__c).Clear();");
						}
						w.Open("foreach (var __i in __v)");
						w.Line("__s = __i;");
						w.Line("((" + coll + ")__c).Add(" + conv + ");");
						w.Close();
						if (a.Shape == CollectionShape.Create) w.Line(target + " = __c;");
						break;
				}
				w.Close();
				w.Open("catch (global::System.Exception __ex) when (!(__ex is " + exc + "))");
				w.Line("throw " + G + ".ConversionError(__b, " + a.Id + ", __s, __ex);");
				w.Close();
				w.Close();
			}
			if (m.HasNamedGroups) w.Line("result.ArgumentGroup = __b.Group.Name;");
			w.Line("return result;");
			w.Close();
		}

		static void EmitDispose(Writer w, TypeModel m, string G)
		{
			w.Line();
			w.Line("/// <summary>");
			w.Line("/// Disposes every [CmdArg] member holding a disposable value, including the items of collection members,");
			w.Line("/// but never the console's standard streams. Members that were disposed are set to null (or emptied when they");
			w.Line("/// can't be assigned), so calling this again does nothing.");
			w.Line("/// </summary>");
			w.Open("public void Dispose()");
			foreach (var a in m.Args.Where(a => a.MayDispose))
			{
				string target = "this." + Ident(a.MemberName);
				if (a.Settable)
				{
					w.Line("if (" + G + ".DisposeArgument(" + target + ")) " + target + " = null;");
				}
				else if (a.Shape != CollectionShape.None)
				{
					w.Line("if (" + G + ".DisposeArgument(" + target + ")) ((global::System.Collections.Generic.ICollection<" + a.ElementType + ">)" + target + ").Clear();");
				}
				else
				{
					w.Line(G + ".DisposeArgument(" + target + ");");
				}
			}
			w.Close();
		}

		static string Lit(string? s)
		{
			if (s == null) return "null";
			var sb = new StringBuilder("\"");
			foreach (var c in s)
			{
				switch (c)
				{
					case '\\': sb.Append("\\\\"); break;
					case '"': sb.Append("\\\""); break;
					case '\n': sb.Append("\\n"); break;
					case '\r': sb.Append("\\r"); break;
					case '\t': sb.Append("\\t"); break;
					default:
						if (c < ' ' || c > '~') sb.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
						else sb.Append(c);
						break;
				}
			}
			return sb.Append('"').ToString();
		}

		static string Ident(string name)
			=> Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(name) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None ? "@" + name : name;

		static string CharLit(char c)
		{
			if (c == '\0') return "'\\0'";
			if (c == '\'' || c == '\\') return "'\\" + c + "'";
			if (c < ' ' || c > '~') return "'\\u" + ((int)c).ToString("x4", CultureInfo.InvariantCulture) + "'";
			return "'" + c + "'";
		}
	}
}
